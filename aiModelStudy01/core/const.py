"""核心常量定义"""
from enum import Enum


class Provider(str, Enum):
    """支持的 AI 模型提供商"""
    MINIMAX = "minimax"
    OPENAI = "openai"
    ANTHROPIC = "anthropic"


class MessageRole(str, Enum):
    """消息角色"""
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


